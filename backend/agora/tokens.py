"""RTC + RTM tokens for the browser user (AccessToken2, built by Agora's official SDK).

The agent's own token is generated by the SDK when it starts the agent.
"""

from __future__ import annotations

from agora_agent import generate_client_token

from config import Settings

TOKEN_TTL_SECONDS = 4 * 60 * 60


def user_token(settings: Settings, channel: str, uid: int) -> str:
    """Token that lets the browser join `channel` as `uid`, publish audio and log in to RTM."""
    return generate_client_token(
        app_id=settings.agora_app_id,
        app_certificate=settings.agora_app_certificate.get_secret_value(),
        channel_name=channel,
        uid=uid,
        token_expire=TOKEN_TTL_SECONDS,
    )
